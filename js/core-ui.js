function convertScript(str, mode = currentScriptMode) {
  if (!str) return '';
  ensureOpenCCInitialized();
  if (mode === 'simp') {
    if (openccToSimp) return openccToSimp(str);
    return str.split('').map(c => FALLBACK_T2S[c] || c).join('');
  }
  if (openccToTrad) return openccToTrad(str);
  return str.split('').map(c => FALLBACK_S2T[c] || c).join('');
}

function switchScriptMode(mode) {
  const chkTrad = document.getElementById('chkTrad');
  const chkSimp = document.getElementById('chkSimp');
  const extTrad = document.getElementById('extChkTrad');
  const extSimp = document.getElementById('extChkSimp');

  if (mode === 'trad') {
    currentScriptMode = 'trad';
    if (chkTrad) chkTrad.checked = true;
    if (chkSimp) chkSimp.checked = false;
    if (extTrad) extTrad.checked = true;
    if (extSimp) extSimp.checked = false;
  } else if (mode === 'simp') {
    currentScriptMode = 'simp';
    if (chkSimp) chkSimp.checked = true;
    if (chkTrad) chkTrad.checked = false;
    if (extSimp) extSimp.checked = true;
    if (extTrad) extTrad.checked = false;
  }
  try { localStorage.setItem('tp_script_mode', currentScriptMode); } catch (e) {}

  updateRowVisibility();
  document.querySelectorAll('.tp-zh').forEach(el => {
    const raw = el.dataset.raw || el.innerText;
    el.dataset.raw = raw;
    el.innerText = convertScript(raw, currentScriptMode);
  });
  if (typeof renderMnemonicsPack === 'function') renderMnemonicsPack();
}

function updateRowVisibility() {
  const card = document.getElementById('sheetCard');
  const studioTop = document.getElementById('studioTopPane');
  const chkTrad = document.getElementById('chkTrad');
  const chkSimp = document.getElementById('chkSimp');
  const hideZh = chkTrad && chkSimp && !chkTrad.checked && !chkSimp.checked;
  [card, studioTop].forEach(el => {
    if (!el) return;
    el.classList.toggle('hide-en', !document.getElementById('chkEn').checked);
    el.classList.toggle('hide-tp', !document.getElementById('chkTp').checked);
    el.classList.toggle('hide-std', !document.getElementById('chkStd').checked);
    el.classList.toggle('hide-zh', Boolean(hideZh));
  });
}

