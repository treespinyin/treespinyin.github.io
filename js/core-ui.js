async function fetchCloudDocumentByUrl(rawUrl) {
  const cleanDocText = (txt) => {
    if (!txt || typeof txt !== 'string') return '';
    const trimmed = txt.replace(/^\uFEFF/, '').trim();
    if (!trimmed || /^<!DOCTYPE html>|^<html/i.test(trimmed)) return '';
    if (/Google Accounts|Sign in - Google|ServiceLogin/i.test(trimmed.slice(0, 400))) return '';
    return trimmed;
  };

  const gdocMatch = rawUrl.match(/\/document\/d\/([a-zA-Z0-9_-]+)/) || rawUrl.match(/[?&]id=([a-zA-Z0-9_-]+)/);
  if (gdocMatch) {
    const docId = gdocMatch[1];
    const exportUrl = `https://docs.google.com/document/d/${docId}/export?format=txt`;
    const tasks = [
      fetchWithTimeout(exportUrl, { credentials: 'omit' }, 6000)
        .then(r => { if (!r.ok) throw new Error('err'); return r.text(); })
        .then(t => { const c = cleanDocText(t); if (c) return c; throw new Error('empty'); }),
      fetchWithTimeout(`https://api.allorigins.win/raw?url=${encodeURIComponent(exportUrl)}`, {}, 6500)
        .then(r => { if (!r.ok) throw new Error('err'); return r.text(); })
        .then(t => { const c = cleanDocText(t); if (c) return c; throw new Error('empty'); }),
      fetchWithTimeout(`https://r.jina.ai/${exportUrl}`, {}, 6500)
        .then(r => { if (!r.ok) throw new Error('err'); return r.text(); })
        .then(t => {
          const stripped = t.replace(/^Title:.*?\n+/s, '').replace(/^URL Source:.*?\n+/m, '').replace(/^Markdown Content:\s*/m, '').trim();
          const c = cleanDocText(stripped);
          if (c) return c;
          throw new Error('empty');
        }),
      fetchWithTimeout(`https://api.codetabs.com/v1/proxy?quest=${encodeURIComponent(exportUrl)}`, {}, 6500)
        .then(r => { if (!r.ok) throw new Error('err'); return r.text(); })
        .then(t => { const c = cleanDocText(t); if (c) return c; throw new Error('empty'); })
    ];
    try {
      return await Promise.any(tasks);
    } catch (e) {}
  }

  const gdriveMatch = rawUrl.match(/\/file\/d\/([a-zA-Z0-9_-]+)/);
  if (gdriveMatch) {
    const fileId = gdriveMatch[1];
    const dlUrl = `https://drive.google.com/uc?export=download&id=${fileId}`;
    const tasks = [
      fetchWithTimeout(`https://api.allorigins.win/raw?url=${encodeURIComponent(dlUrl)}`, {}, 6500)
        .then(r => { if (!r.ok) throw new Error('err'); return r.text(); })
        .then(t => { const c = cleanDocText(t); if (c) return c; throw new Error('empty'); }),
      fetchWithTimeout(`https://api.codetabs.com/v1/proxy?quest=${encodeURIComponent(dlUrl)}`, {}, 6500)
        .then(r => { if (!r.ok) throw new Error('err'); return r.text(); })
        .then(t => { const c = cleanDocText(t); if (c) return c; throw new Error('empty'); })
    ];
    try {
      return await Promise.any(tasks);
    } catch (e) {}
  }
  return '';
}

